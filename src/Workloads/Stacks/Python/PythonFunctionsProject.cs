using System.Diagnostics;
using System.Text.RegularExpressions;
using Azure.Functions.Cli.Common;
using Azure.Functions.Cli.Projects;
using Azure.Functions.Cli.Workers;

namespace Azure.Functions.Cli.Workloads.Python;

/// <summary>
/// Python Functions project. Before the host runs, prepares the project's
/// environment and points the worker at its interpreter so the user's deps are
/// resolvable. uv-managed projects (see <see cref="PythonPackageManagerDetector"/>)
/// are synced with <c>uv sync</c>; other projects resolve a virtual environment
/// (honoring <c>$VIRTUAL_ENV</c> or a pre-existing <c>.venv</c> / <c>venv</c> /
/// <c>env</c> folder, otherwise creating <c>.venv</c>) and install
/// <c>requirements.txt</c> into it with pip.
/// </summary>
internal sealed class PythonFunctionsProject : FunctionsProject
{
    internal const string DefaultVenvFolderName = ".venv";
    internal const string IsolateWorkerDepsEnvVar = "PYTHON_ISOLATE_WORKER_DEPENDENCIES";
    internal const string WorkerExecutablePathEnvVar = "languageWorkers__python__defaultExecutablePath";
    internal const string WorkerRuntimeVersionEnvVar = "FUNCTIONS_WORKER_RUNTIME_VERSION";
    internal const string WorkerDirectoryEnvVar = "languageWorkers__python__workerDirectory";
    internal const string VirtualEnvEnvVar = "VIRTUAL_ENV";
    internal const string UvProjectEnvironmentEnvVar = "UV_PROJECT_ENVIRONMENT";
    internal const string UvInstallUrl = "https://docs.astral.sh/uv/getting-started/installation/";
    internal const string UvExportHeader = "# This file was autogenerated by uv";
    private const string RequirementsFileName = PythonPackageManagerDetector.RequirementsFileName;

    // Conventional venv folder names to look for in the project root before
    // creating a new one. Order matters: most-common first.
    private static readonly string[] _venvFolderCandidates = [".venv", "venv", "env", ".virtualenv"];
    private static readonly string[] _uvExportArguments = ["export", "--frozen", "--no-dev", "--no-hashes", "--no-editable"];

    private readonly WorkingDirectory _workingDirectory;
    private readonly FunctionsWorkerReference _workerReference;

    public PythonFunctionsProject(WorkingDirectory workingDirectory)
    {
        _workingDirectory = workingDirectory ?? throw new ArgumentNullException(nameof(workingDirectory));
        _workerReference = FunctionsWorkerReference.FromWorkload("python");
    }

    // Internal seams so tests can stub interpreter / pip / uv invocations. stdout and stderr lines are streamed
    // to the callbacks as the process produces them, and the task yields the process exit code.
    internal Func<string, string, Action<string>, Action<string>, CancellationToken, Task<int>> RunCreateVenv { get; set; } = DefaultRunCreateVenv;

    internal Func<string, string, string, Action<string>, Action<string>, CancellationToken, Task<int>> RunPipInstall { get; set; } = DefaultRunPipInstall;

    internal Func<string, CancellationToken, Task<string?>> ReadPythonVersion { get; set; } = DefaultReadPythonVersion;

    internal Func<string, string?> ReadEnvironmentVariable { get; set; } = Environment.GetEnvironmentVariable;

    internal Func<string?> FindUv { get; set; } = UvLocator.Find;

    internal Func<string> GetRuntimeIdentifier { get; set; } = PythonSupportedVersions.GetCurrentRuntimeIdentifier;

    // (workerDirectory, runtimeIdentifier) -> major.minor versions that have a worker payload for the platform.
    internal Func<string, string, IReadOnlyList<string>> ReadWorkerPayloadVersions { get; set; } = DefaultReadWorkerPayloadVersions;

    // (projectRoot, uvPath, onOutputLine, onErrorLine, ct) -> exit code.
    internal Func<string, string, Action<string>, Action<string>, CancellationToken, Task<int>> RunUvSync { get; set; } = DefaultRunUvSync;

    // (projectRoot, uvPath, arguments, onErrorLine, ct) -> (exit code, captured stdout).
    internal Func<string, string, IReadOnlyList<string>, Action<string>, CancellationToken, Task<(int ExitCode, string Output)>> RunUvExport { get; set; } = DefaultRunUvExport;

    public override WorkingDirectory WorkingDirectory => _workingDirectory;

    public override string StackName => "python";

    public override string StackDisplayName => "Python";

    public override bool SupportsExtensionBundles => true;

    public override FunctionsWorkerReference WorkerReference => _workerReference;

    public override async Task PrepareForHostRunAsync(FunctionsProjectHostRunContext context, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(context);
        cancellationToken.ThrowIfCancellationRequested();

        // Python has no compile step, so --no-build (context.SkipBuild) is a no-op
        // here: environment sync and package install are restore, not build.
        string root = _workingDirectory.Info.FullName;

        if (PythonPackageManagerDetector.Detect(root) == PythonPackageManager.Uv)
        {
            string? uv = FindUv();
            if (uv is not null)
            {
                string envPath = await PrepareUvEnvironmentAsync(context, root, uv, cancellationToken).ConfigureAwait(false);
                await ConfigureWorkerAsync(context, envPath, PythonPackageManager.Uv, cancellationToken).ConfigureAwait(false);
                return;
            }

            if (!File.Exists(Path.Combine(root, RequirementsFileName)))
            {
                throw new GracefulException(
                    $"uv was not found on PATH and this project has no {RequirementsFileName}. Install uv ({UvInstallUrl}) or add a {RequirementsFileName}.",
                    isUserError: true);
            }

            context.Reporter.WriteLog(
                $"This project uses uv, but uv was not found on PATH. Falling back to pip with {RequirementsFileName}. Install uv: {UvInstallUrl}",
                FunctionsProjectReportSeverity.Warning);
        }

        string venvPath = await PreparePipEnvironmentAsync(context, root, cancellationToken).ConfigureAwait(false);
        await ConfigureWorkerAsync(context, venvPath, PythonPackageManager.Pip, cancellationToken).ConfigureAwait(false);
    }

    internal static string GetVenvExecutablePath(string venvPath, string executable)
    {
        string folder = OperatingSystem.IsWindows() ? "Scripts" : "bin";
        string name = OperatingSystem.IsWindows() ? executable + ".exe" : executable;
        return Path.Combine(venvPath, folder, name);
    }

    private async Task<string> PrepareUvEnvironmentAsync(FunctionsProjectHostRunContext context, string root, string uv, CancellationToken cancellationToken)
    {
        context.Reporter.ReportStatus("Syncing Python environment with uv");

        // uv writes progress (and errors) to stderr; stream it as regular output and let the
        // exit code decide failure so routine progress lines aren't rendered as errors.
        int exitCode = await RunUvSync(
            root,
            uv,
            line => context.Reporter.WriteLog(line, FunctionsProjectReportSeverity.Info),
            line => context.Reporter.WriteLog(line, FunctionsProjectReportSeverity.Info),
            cancellationToken).ConfigureAwait(false);

        if (exitCode != 0)
        {
            throw new GracefulException(
                $"'uv sync' failed (exit {exitCode}). Run 'uv sync' in {root} to see uv's full diagnostics.",
                isUserError: true);
        }

        // uv only uses the project environment (never $VIRTUAL_ENV unless --active), so follow it.
        string envPath = ResolveUvProjectEnvironment(root);
        string python = GetVenvExecutablePath(envPath, "python");
        if (!File.Exists(python))
        {
            throw new GracefulException(
                $"No Python interpreter found at {python}. Check {UvProjectEnvironmentEnvVar} or re-run 'uv sync'.",
                isUserError: true);
        }

        await TryExportRequirementsAsync(context, root, uv, cancellationToken).ConfigureAwait(false);
        return envPath;
    }

    private string ResolveUvProjectEnvironment(string root)
    {
        string? configured = ReadEnvironmentVariable(UvProjectEnvironmentEnvVar);
        if (string.IsNullOrWhiteSpace(configured))
        {
            return Path.Combine(root, DefaultVenvFolderName);
        }

        return Path.GetFullPath(configured, root);
    }

    // Exports dependencies for downstream builds that install from requirements.txt.
    // User-authored files are never overwritten.
    private async Task TryExportRequirementsAsync(FunctionsProjectHostRunContext context, string root, string uv, CancellationToken cancellationToken)
    {
        string requirementsPath = Path.Combine(root, RequirementsFileName);

        try
        {
            if (File.Exists(requirementsPath) && !IsUvGenerated(requirementsPath))
            {
                context.Reporter.WriteLog(
                    $"{RequirementsFileName} was not generated by uv and was left unchanged; it may be out of sync with uv.lock.",
                    FunctionsProjectReportSeverity.Warning);
                return;
            }

            (int exitCode, string output) = await RunUvExport(
                root,
                uv,
                _uvExportArguments,
                line => context.Reporter.WriteLog(line, FunctionsProjectReportSeverity.Info),
                cancellationToken).ConfigureAwait(false);

            if (exitCode != 0)
            {
                context.Reporter.WriteLog(
                    $"'uv export' failed (exit {exitCode}); {RequirementsFileName} was not updated.",
                    FunctionsProjectReportSeverity.Warning);
                return;
            }

            string? existing = File.Exists(requirementsPath) ? File.ReadAllText(requirementsPath) : null;
            if (existing is not null && existing.ReplaceLineEndings("\n") == output.ReplaceLineEndings("\n"))
            {
                return;
            }

            File.WriteAllText(requirementsPath, output);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            context.Reporter.WriteLog(
                $"Could not update {RequirementsFileName}: {ex.Message}",
                FunctionsProjectReportSeverity.Warning);
        }
    }

    private static bool IsUvGenerated(string requirementsPath)
    {
        foreach (string line in File.ReadLines(requirementsPath))
        {
            if (!string.IsNullOrWhiteSpace(line))
            {
                return line.TrimStart().StartsWith(UvExportHeader, StringComparison.Ordinal);
            }
        }

        // An empty file carries nothing worth preserving.
        return true;
    }

    private async Task<string> PreparePipEnvironmentAsync(FunctionsProjectHostRunContext context, string root, CancellationToken cancellationToken)
    {
        (string venvPath, bool venvAlreadyExisted) = ResolveVenvPath(root);

        if (!venvAlreadyExisted)
        {
            context.Reporter.ReportStatus($"Creating Python virtual environment in {Path.GetFileName(venvPath)}");

            int exitCode = await RunCreateVenv(
                root,
                venvPath,
                line => context.Reporter.WriteLog(line, FunctionsProjectReportSeverity.Info),
                line => context.Reporter.WriteLog(line, FunctionsProjectReportSeverity.Error),
                cancellationToken).ConfigureAwait(false);

            if (exitCode != 0)
            {
                throw new GracefulException(
                    $"'python -m venv {Path.GetFileName(venvPath)}' failed (exit {exitCode}).",
                    isUserError: true);
            }
        }

        string venvPython = GetVenvExecutablePath(venvPath, "python");
        string? majorMinor = await ReadPythonVersion(venvPython, cancellationToken).ConfigureAwait(false);
        if (!string.IsNullOrEmpty(majorMinor) && !IsSupportedPythonVersion(majorMinor))
        {
            throw new GracefulException(
                $"Python {majorMinor} is not supported. Install Python 3.10 or later and recreate the virtual environment.",
                isUserError: true);
        }

        string requirementsPath = Path.Combine(root, RequirementsFileName);
        if (File.Exists(requirementsPath))
        {
            context.Reporter.ReportStatus($"Installing Python dependencies from {RequirementsFileName}");

            string pipPath = GetVenvExecutablePath(venvPath, "pip");
            int exitCode = await RunPipInstall(
                root,
                pipPath,
                requirementsPath,
                line => context.Reporter.WriteLog(line, FunctionsProjectReportSeverity.Info),
                line => context.Reporter.WriteLog(line, FunctionsProjectReportSeverity.Error),
                cancellationToken).ConfigureAwait(false);

            if (exitCode != 0)
            {
                throw new GracefulException(
                    $"'pip install -r {RequirementsFileName}' failed (exit {exitCode}).",
                    isUserError: true);
            }
        }

        return venvPath;
    }

    // Shared by the uv and pip paths: isolates worker deps, points the worker at the
    // environment's interpreter, and sets/validates the worker runtime version.
    private async Task ConfigureWorkerAsync(
        FunctionsProjectHostRunContext context,
        string envPath,
        PythonPackageManager manager,
        CancellationToken cancellationToken)
    {
        // Pin worker deps to the venv so a global site-packages can't shadow it.
        context.EnvironmentVariables[IsolateWorkerDepsEnvVar] = "1";

        // Point the host at the venv interpreter so the worker process actually has
        // the packages we just installed. Without this, the host falls back to
        // the system Python and `import <user-dep>` fails at runtime.
        string python = GetVenvExecutablePath(envPath, "python");
        context.EnvironmentVariables[WorkerExecutablePathEnvVar] = python;

        // Tell the host which Python worker to load (3.10 vs 3.13 etc.).
        string? majorMinor = await ReadPythonVersion(python, cancellationToken).ConfigureAwait(false);
        if (string.IsNullOrEmpty(majorMinor) || !Version.TryParse(majorMinor, out Version? found))
        {
            context.Reporter.WriteLog(
                $"Could not determine the Python version of {python}; {WorkerRuntimeVersionEnvVar} was not set and the host will choose a default worker.",
                FunctionsProjectReportSeverity.Warning);
            return;
        }

        string rid = GetRuntimeIdentifier();
        IReadOnlyList<string> payloadVersions = context.EnvironmentVariables.TryGetValue(WorkerDirectoryEnvVar, out string? workerDirectory)
            && !string.IsNullOrWhiteSpace(workerDirectory)
                ? ReadWorkerPayloadVersions(workerDirectory, rid)
                : [];
        bool fromPayload = payloadVersions.Count > 0;
        IReadOnlyList<string> supported = fromPayload ? payloadVersions : PythonSupportedVersions.GetFallback(rid);
        string foundMajorMinor = $"{found.Major}.{found.Minor}";

        if (!supported.Contains(foundMajorMinor, StringComparer.Ordinal))
        {
            Version newest = supported.Select(Version.Parse).Max()!;

            // The fallback table can lag new Python releases; only the installed payload is authoritative.
            if (!fromPayload && found > newest)
            {
                context.Reporter.WriteLog(
                    $"Python {majorMinor} is newer than the latest version known to be supported by the Azure Functions Python worker on {rid} ({newest}). Continuing; the host may fail to start the worker.",
                    FunctionsProjectReportSeverity.Warning);
            }
            else
            {
                string fix = manager == PythonPackageManager.Uv
                    ? $"Run 'uv python pin {PythonSupportedVersions.GetDefault(supported)}' and 'uv sync'."
                    : $"Recreate the virtual environment at {envPath} with a supported Python version.";
                throw new GracefulException(
                    $"Python {majorMinor} is not supported by the Azure Functions Python worker on {rid} (supported: {string.Join(", ", supported)}). {fix}",
                    isUserError: true);
            }
        }

        context.EnvironmentVariables[WorkerRuntimeVersionEnvVar] = majorMinor;
    }

    private static bool IsSupportedPythonVersion(string majorMinor)
        => Version.TryParse(majorMinor, out Version? version) && version.Major == 3 && version.Minor >= 10;

    // Pick the venv to use, in priority order:
    //   1. $VIRTUAL_ENV (set by the `activate` script) so an explicitly-activated
    //      venv wins, even if it lives outside the project.
    //   2. Any conventional folder already present at the project root
    //      (.venv, venv, env, .virtualenv).
    //   3. Fall back to creating .venv inside the project root.
    // Returns the resolved venv path and whether it already exists on disk; the
    // caller skips `python -m venv` when it does.
    private (string Path, bool AlreadyExists) ResolveVenvPath(string projectRoot)
    {
        string? activated = ReadEnvironmentVariable(VirtualEnvEnvVar);
        if (!string.IsNullOrWhiteSpace(activated) && Directory.Exists(activated))
        {
            return (activated, true);
        }

        foreach (string candidate in _venvFolderCandidates)
        {
            string candidatePath = Path.Combine(projectRoot, candidate);
            if (Directory.Exists(candidatePath))
            {
                return (candidatePath, true);
            }
        }

        return (Path.Combine(projectRoot, DefaultVenvFolderName), false);
    }

    private static async Task<int> DefaultRunCreateVenv(
        string workingDirectory,
        string venvPath,
        Action<string> onOutputLine,
        Action<string> onErrorLine,
        CancellationToken cancellationToken)
    {
        // Prefer `python3` on POSIX so we don't pick up a Python 2 shim. If the
        // interpreter isn't on PATH (Win32Exception from Process.Start), retry
        // with `python` so we work on Windows and pyenv setups that only expose
        // the unversioned name.
        string[] interpreters = OperatingSystem.IsWindows()
            ? ["python", "python3"]
            : ["python3", "python"];

        foreach (string interpreter in interpreters)
        {
            (int exitCode, bool launched) = await PythonProcessRunner.TryRunStreamingAsync(
                interpreter,
                ["-m", "venv", venvPath],
                workingDirectory,
                onOutputLine,
                onErrorLine,
                cancellationToken).ConfigureAwait(false);

            if (launched)
            {
                return exitCode;
            }
        }

        onErrorLine("No Python interpreter was found.");
        return -1;
    }

    private static async Task<int> DefaultRunPipInstall(
        string workingDirectory,
        string pipPath,
        string requirementsPath,
        Action<string> onOutputLine,
        Action<string> onErrorLine,
        CancellationToken cancellationToken)
    {
        (int exitCode, _) = await PythonProcessRunner.TryRunStreamingAsync(
            pipPath,
            ["install", "-r", requirementsPath],
            workingDirectory,
            onOutputLine,
            onErrorLine,
            cancellationToken).ConfigureAwait(false);

        return exitCode;
    }

    private static async Task<int> DefaultRunUvSync(
        string workingDirectory,
        string uvPath,
        Action<string> onOutputLine,
        Action<string> onErrorLine,
        CancellationToken cancellationToken)
    {
        (int exitCode, bool launched) = await PythonProcessRunner.TryRunStreamingAsync(
            uvPath,
            ["sync"],
            workingDirectory,
            onOutputLine,
            onErrorLine,
            cancellationToken).ConfigureAwait(false);

        if (!launched)
        {
            onErrorLine($"Failed to start '{uvPath}'.");
        }

        return exitCode;
    }

    private static Task<(int ExitCode, string Output)> DefaultRunUvExport(
        string workingDirectory,
        string uvPath,
        IReadOnlyList<string> arguments,
        Action<string> onErrorLine,
        CancellationToken cancellationToken)
        => PythonProcessRunner.RunCapturingAsync(
            uvPath,
            arguments,
            workingDirectory,
            onErrorLine,
            cancellationToken);

    // The host loads `<version>/<os>/<architecture>/worker.py` relative to the worker directory.
    private static IReadOnlyList<string> DefaultReadWorkerPayloadVersions(string workerDirectory, string runtimeIdentifier)
    {
        if (!Directory.Exists(workerDirectory))
        {
            return [];
        }

        (string os, string architecture) = PythonSupportedVersions.GetWorkerPlatform(runtimeIdentifier);
        return Directory.EnumerateDirectories(workerDirectory)
            .Select(Path.GetFileName)
            .OfType<string>()
            .Where(name => Version.TryParse(name, out Version? v) && v.Build < 0
                && File.Exists(Path.Combine(workerDirectory, name, os, architecture, "worker.py")))
            .OrderBy(Version.Parse)
            .ToList();
    }

    private static async Task<string?> DefaultReadPythonVersion(string pythonPath, CancellationToken cancellationToken)
    {
        try
        {
            var psi = new ProcessStartInfo
            {
                FileName = pythonPath,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            };
            psi.ArgumentList.Add("--version");

            using var process = Process.Start(psi);
            if (process is null)
            {
                return null;
            }

            Task<string> stdoutTask = process.StandardOutput.ReadToEndAsync(cancellationToken);
            Task<string> stderrTask = process.StandardError.ReadToEndAsync(cancellationToken);
            await Task.WhenAll(stdoutTask, stderrTask).ConfigureAwait(false);
            await process.WaitForExitAsync(cancellationToken).ConfigureAwait(false);

            if (process.ExitCode != 0)
            {
                return null;
            }

            // `python --version` historically printed to stderr (Python 2) and now
            // prints to stdout (Python 3). Inspect both so we don't miss it.
            string raw = stdoutTask.Result + " " + stderrTask.Result;
            Match match = Regex.Match(raw, @"Python\s+(\d+)\.(\d+)");
            return match.Success ? $"{match.Groups[1].Value}.{match.Groups[2].Value}" : null;
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            return null;
        }
    }
}
