using System.Collections.ObjectModel;
using Azure.Functions.Cli.Common;

namespace Azure.Functions.Cli.Templates.Native;

/// <summary>
/// Identifies qualification stages without granting execution permission.
/// </summary>
[Flags]
public enum NativeTemplatePolicyStages
{
    None = 0,
    Invocation = 1,
    CapturedOutput = 2,
    Effects = 4,
}

/// <summary>
/// Exposes one host-issued invocation's final values and source within its lifetime.
/// </summary>
public abstract class NativeTemplateInvocationContext
{
    public abstract NativeTemplateSource Source { get; }
    public abstract WorkingDirectory ProjectDirectory { get; }
    public abstract WorkingDirectory OutputDirectory { get; }
    public abstract string? Name { get; }
    public abstract bool DryRun { get; }
    public abstract bool Force { get; }
    public abstract IReadOnlyDictionary<string, string?> CanonicalValues { get; }
    public abstract IReadOnlySet<string> ExplicitParameterNames { get; }
    public abstract NativeTemplateProjectBinding? ProjectBinding { get; }
    public abstract Task RevalidateAsync(CancellationToken cancellationToken);
}

/// <summary>
/// Describes an actual regular file and its independently pinned original and generated bytes.
/// </summary>
public sealed record NativeTemplateCapturedFile(string TargetRelativePath, string SourceRelativePath, NativeTemplateSourceStamp Source, string Sha256);

/// <summary>
/// Exposes copied bytes and facts from the current sealed native image, not the live target.
/// </summary>
public abstract class NativeTemplateCapturedOutput
{
    public abstract NativeTemplateInvocationContext Invocation { get; }
    public abstract IReadOnlyList<NativeTemplateCapturedFile> Files { get; }
    public abstract IReadOnlyList<string> Directories { get; }
    public abstract IReadOnlyList<string> PrimaryOutputs { get; }
    public abstract Task<ReadOnlyMemory<byte>> ReadFileAsync(string targetRelativePath, CancellationToken cancellationToken);
    public abstract Task RevalidateAsync(CancellationToken cancellationToken);
}

/// <summary>
/// Carries evaluated project values while the host supplies selected-source authority.
/// </summary>
public sealed record NativeTemplateProjectBinding(string ProjectPath, string TargetFramework, string RootNamespace);

/// <summary>
/// Returns bounded defaults, source pins and binding values without modifying an invocation.
/// </summary>
public sealed record NativeTemplateInvocationQualification(
    bool Succeeded, IReadOnlyList<string> Diagnostics, IReadOnlyDictionary<string, string?> CanonicalDefaults,
    IReadOnlyList<NativeTemplateSourceStamp> RequiredSources, NativeTemplateProjectBinding? ProjectBinding = null)
{
    public IReadOnlyList<string> Diagnostics { get; } = Array.AsReadOnly<string>([.. Diagnostics ?? throw new ArgumentNullException(nameof(Diagnostics))]);

    public IReadOnlyDictionary<string, string?> CanonicalDefaults { get; } = new ReadOnlyDictionary<string, string?>(
        new Dictionary<string, string?>(CanonicalDefaults ?? throw new ArgumentNullException(nameof(CanonicalDefaults)), StringComparer.Ordinal));

    public IReadOnlyList<NativeTemplateSourceStamp> RequiredSources { get; } =
        Array.AsReadOnly<NativeTemplateSourceStamp>([.. RequiredSources ?? throw new ArgumentNullException(nameof(RequiredSources))]);
}

/// <summary>
/// Declares a single owner-qualified project anchor before catalog eligibility.
/// </summary>
public sealed record NativeTemplateProjectAnchor(int PrimaryOutputIndex, string Stack, string Language);

/// <summary>
/// Describes the existing bounded repair before the terminal evaluated compile include.
/// </summary>
public sealed record NativeTemplateCompileRepair(
    string ProjectPath, string ExpectedProjectSha256, IReadOnlyList<string> EvaluatedCompileOrder,
    IReadOnlyList<NativeTemplateCapturedFile> GeneratedFiles)
{
    public IReadOnlyList<string> EvaluatedCompileOrder { get; } =
        Array.AsReadOnly<string>([.. EvaluatedCompileOrder ?? throw new ArgumentNullException(nameof(EvaluatedCompileOrder))]);

    public IReadOnlyList<NativeTemplateCapturedFile> GeneratedFiles { get; } =
        Array.AsReadOnly<NativeTemplateCapturedFile>([.. GeneratedFiles ?? throw new ArgumentNullException(nameof(GeneratedFiles))]);
}

/// <summary>
/// Qualifies the current capture without replacing its source-declared project anchor.
/// </summary>
public sealed record NativeTemplateCaptureQualification(
    bool Succeeded, IReadOnlyList<string> Diagnostics, NativeTemplateCompileRepair? CompileRepair = null)
{
    public IReadOnlyList<string> Diagnostics { get; } = Array.AsReadOnly<string>([.. Diagnostics ?? throw new ArgumentNullException(nameof(Diagnostics))]);
}
